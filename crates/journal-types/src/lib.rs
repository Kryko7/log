impl EntryFrontmatter {
    /// Construct frontmatter with a fresh UUID v7 and current UTC timestamp.
    pub fn new(title: impl Into<String>) -> Self {
        let now = Utc::now();
        Self {
            id: Uuid::now_v7(),
            title: title.into(),
            date: now,
            updated_at: now,
            notebook_id: None,
            tags: Vec::new(),
            mood: None,
            starred: false,
            source: Some("log".to_string()),
            source_id: None,
            weather: None,
            location: None,
            stamps: Vec::new(),
            photos: Vec::new(),
            audio: Vec::new(),
            links: Vec::new(),
        }
    }
}

