//! Pure Rust shared domain models and API contracts for **Log**.
//!
//! This crate intentionally depends only on `serde`, `serde_json`, `chrono`,
//! and `uuid` (with `js` support) so it compiles identically on `x86_64`
//! native targets and `wasm32-unknown-unknown` frontend targets.

use chrono::{DateTime, NaiveDate, Utc};
use serde::{Deserialize, Serialize};
use uuid::Uuid;

/// Complete journal entry loaded from Markdown + YAML frontmatter.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Entry {
    /// Stable UUID (v7 preferred for chronological sorting).
    pub id: Uuid,
    /// Structured YAML frontmatter metadata.
    pub frontmatter: EntryFrontmatter,
    /// Raw UTF-8 Markdown body content.
    pub body: String,
    /// Optional pre-rendered HTML preview generated by `journal-core`.
    #[serde(default)]
    pub html_preview: Option<String>,
    /// Vault-relative path (e.g., `2026/11/2026-11-15-quiet-rain.md`).
    #[serde(default)]
    pub path: String,
    /// Word count computed from the Markdown body.
    #[serde(default)]
    pub word_count: usize,
    /// Estimated reading duration in whole minutes (minimum 1 when non-empty).
    #[serde(default)]
    pub reading_minutes: u32,
    /// Entries that link to this entry via `[[wikilinks]]`.
    #[serde(default)]
    pub backlinks: Vec<BacklinkRef>,
}

impl Entry {
    /// Construct a new entry with computed word count and reading time.
    pub fn new(frontmatter: EntryFrontmatter, body: impl Into<String>, path: impl Into<String>) -> Self {
        let body = body.into();
        let word_count = Self::count_words(&body);
        let reading_minutes = Self::estimate_reading_minutes(word_count);
        Self {
            id: frontmatter.id,
            frontmatter,
            body,
            html_preview: None,
            path: path.into(),
            word_count,
            reading_minutes,
            backlinks: Vec::new(),
        }
    }

    /// Count words in a Markdown string, ignoring frontmatter fences if absent.
    pub fn count_words(markdown: &str) -> usize {
        markdown.split_whitespace().count()
    }

    /// Estimate reading time at ~210 words per minute (returns 0 for empty body).
    pub fn estimate_reading_minutes(word_count: usize) -> u32 {
        if word_count == 0 {
            0
        } else {
            ((word_count as f32 / 210.0).ceil() as u32).max(1)
        }
    }

    /// Build a lightweight [`EntrySummary`] from this full entry.
    pub fn to_summary(&self) -> EntrySummary {
        let snippet = Self::build_snippet(&self.body, 180);
        EntrySummary {
            id: self.id,
            title: self.frontmatter.title.clone(),
            date: self.frontmatter.date,
            updated_at: self.frontmatter.updated_at,
            notebook_id: self.frontmatter.notebook_id.clone(),
            tags: self.frontmatter.tags.clone(),
            mood: self.frontmatter.mood.clone(),
            starred: self.frontmatter.starred,
            snippet,
            word_count: self.word_count,
            reading_minutes: self.reading_minutes,
            path: self.path.clone(),
            cover_photo: self
                .frontmatter
                .photos
                .first()
                .map(|p| p.thumbnail_url.clone().unwrap_or_else(|| p.url.clone())),
            has_audio: !self.frontmatter.audio.is_empty(),
            has_photos: !self.frontmatter.photos.is_empty(),
            weather: self.frontmatter.weather.clone(),
            location: self.frontmatter.location.clone(),
            stamps: self.frontmatter.stamps.clone(),
        }
    }

    /// Create a plain-text excerpt truncated cleanly at word boundaries.
    pub fn build_snippet(markdown: &str, max_chars: usize) -> String {
        let compact: String = markdown
            .lines()
            .map(str::trim)
            .filter(|l| !l.is_empty() && !l.starts_with('#'))
            .collect::<Vec<_>>()
            .join(" ");
        let cleaned = compact.replace(['*', '_', '`'], "");
        if cleaned.chars().count() <= max_chars {
            return cleaned;
        }
        let mut out: String = cleaned.chars().take(max_chars).collect();
        if let Some(last_space) = out.rfind(' ') {
            out.truncate(last_space);
        }
        format!("{out}…")
    }
}

